package nivel5;

public class Exercicio009Aresta {

	private final int destino;
	private final int peso;
	
	public Exercicio009Aresta(int destino, int peso) {
		this.destino = destino;
		this.peso = peso;
	}

	public int getPeso() {
		return this.peso;
	}

	public int getDestino() {
		return this.destino;
	}
	
	
}
